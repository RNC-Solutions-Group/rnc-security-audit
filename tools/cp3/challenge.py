"""Independently authored CP3 challenge corpus.

This corpus is hand-authored rather than generated by
``tools/cp3/fixtures.py``. It does not reuse that generator's templates, seeds,
or tier conventions. It is still first-party synthetic material, not an
externally sourced corpus, and is reported as its own controlled challenge
rather than combined with Tier 2 or Tier 3.

The committed truth manifest contains hashes and byte spans only. The source
bytes are constructed at test time from harmless synthetic values.
"""

