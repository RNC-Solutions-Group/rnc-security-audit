def _line_for(data: bytes, offset: int) -> int:
    line = 1
    index = 0
    while index < offset:
        if data[index] == 13:
            if index + 1 < offset and data[index + 1] == 10:
                index += 2
            else:
                index += 1
            line += 1
        elif data[index] == 10:
            index += 1
            line += 1
        else:
            index += 1
    return line


def _line_end(data: bytes, start: int, end: int) -> int:
    index = end - 1
    while index > start and data[index] in (10, 13):
        index -= 1
    return _line_for(data, index)


def _truth_item(path: str, data: bytes, start: int, end: int, expectation: Expectation) -> dict:
    token = data[start:end]
    digest = hashlib.sha256(token).hexdigest()
    identity = hashlib.sha256(
        path.encode()
        + b"\0"
        + expectation.rule_id.encode()
        + b"\0"
        + str(start).encode()
        + b"\0"
        + str(end).encode()
        + b"\0"
        + digest.encode()
    ).hexdigest()
    return {
        "finding_id": "challenge-" + identity,
        "dataset_id": "cp3-independent-authored-challenge",
        "dataset_version": "2026.11.2",
        "path": path,
        "classification": "EXPECTED_DETECTION",
        "category": expectation.family,
        "risk_bearing": True,
        "line_start": _line_for(data, start),
        "line_end": _line_end(data, start, end),
        "expected_rule_id": expectation.rule_id,
        "start_byte": start,
        "end_byte": end,
        "secret_sha256": digest,
        "required": True,
        "metadata": {
            "provider_family": expectation.family,
            "credential_type": expectation.credential_type,
            "detector_confidence": expectation.confidence,
        },
    }


def build(root: Path) -> tuple[Path, dict]:
    root.mkdir(parents=True, exist_ok=True)
    values = {key: value.encode("utf-8") for key, value in VALUES.items()}
    items = []
    files = []
    for fixture in _fixtures():
        template = fixture.template.encode("utf-8") if isinstance(fixture.template, str) else fixture.template
        output = bytearray()
        spans: dict[str, list[tuple[int, int]]] = {}
        cursor = 0
        while True:
            start = template.find(b"{{", cursor)
            if start < 0:
                output.extend(template[cursor:])
                break
            end = template.find(b"}}", start + 2)
            if end < 0:
                output.extend(template[cursor:])
                break
            output.extend(template[cursor:start])
            key = template[start + 2 : end].decode("ascii")
            value = values[key]
            begin = len(output)
            output.extend(value)
            spans.setdefault(key, []).append((begin, len(output)))
            cursor = end + 2
        data = bytes(output)
        destination = root / fixture.path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
        files.append(
            {
                "path": fixture.path,
                "byte_length": len(data),
                "sha256": hashlib.sha256(data).hexdigest(),
                "expected_count": len(fixture.expectations),
            }
        )
        for expectation in fixture.expectations:
            occurrences = spans.get(expectation.placeholder, [])[: expectation.occurrences]
            if len(occurrences) != expectation.occurrences:
                raise RuntimeError(
                    f"{fixture.path}: expected {expectation.occurrences} occurrence(s) "
                    f"of {expectation.placeholder}"
                )
            for start, end in occurrences:
                items.append(_truth_item(fixture.path, data, start, end, expectation))
    items.sort(key=lambda item: (item["path"], item["start_byte"], item["expected_rule_id"]))
    document = {
        "schema_version": 1,
        "manifest_id": "cp3-independent-authored-challenge",
        "manifest_version": "2026.11.2",
        "dataset_id": "cp3-independent-authored-challenge",
        "dataset_version": "2026.11.2",
        "source_root": "tests/fixtures/providers/challenge",
        "scoring_policy": {
            "id": "byte-range-v1",
            "version": "1",
            "require_line": True,
            "allow_partial": False,
            "negative_oracle": True,
            "one_to_one": True,
        },
        "items": items,
        "files": files,
        "negative_files": [file["path"] for file in files if file["expected_count"] == 0],
        "counts": {
            "expected_items": len(items),
            "files": len(files),
            "positive_files": sum(1 for file in files if file["expected_count"] > 0),
            "negative_files": sum(1 for file in files if file["expected_count"] == 0),
        },
        "provenance": {
            "generator": "tools/cp3/challenge.py",
            "authorship": (
                "hand-authored independently of tools/cp3/fixtures.py; no shared templates or seed conventions"
            ),
            "source_type": "first-party synthetic challenge, not an externally sourced corpus",
            "detector_output_used": False,
            "fixture_material": "harmless synthetic values; no live credentials",
        },
    }
    return root, document


def write_manifest(document: dict, path: Path = TRUTH) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(document, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return path


