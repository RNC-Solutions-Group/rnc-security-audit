ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
LOWER = "abcdefghijkmnopqrstuvwxyz"


def _repeat(seed: str, alphabet: str, length: int) -> str:
    material = hashlib.sha256(seed.encode("utf-8")).digest()
    output = []
    while len(output) < length:
        for byte in material:
            output.append(alphabet[byte % len(alphabet)])
            if len(output) == length:
                break
        material = hashlib.sha256(material).digest()
    return "".join(output)


def _modern(app_id: str, seed: str) -> str:
    def segment(tag: str, size: int) -> str:
        return _repeat(f"{seed}-{tag}", ALPHABET + LOWER + "0123456789_-", size)

    return f"ghs_{app_id}_{segment('header', 170)}.{segment('payload', 170)}.{segment('signature', 170)}"


